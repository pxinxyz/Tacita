pub(super) fn encode(value: f32) -> u8 {
    let value = value.clamp(0., 1.);
    let mut lo = 0usize;
    let mut hi = 255usize;
    while lo < hi {
        let mid = (lo + hi) / 2;
        if DECODE[mid] < value {
            lo = mid + 1;
        } else {
            hi = mid;
        }
    }
    if lo > 0 && value - DECODE[lo - 1] < DECODE[lo] - value {
        (lo - 1) as u8
    } else {
        lo as u8
    }
}
